export function emergencyText(
  lang: string,
  key: EmergencyMessageKey,
  vars: Record<string, string> = {},
): string {
  const messages = EMERGENCY_MESSAGES[lang] ?? EMERGENCY_MESSAGES.en;
  return messages[key].replace(/\{(\w+)\}/g, (match, name: string) => vars[name] ?? match);
}
