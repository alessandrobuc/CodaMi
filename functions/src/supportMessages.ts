export function supportText(
  lang: string,
  key: SupportMessageKey,
  vars: Record<string, string>,
): string {
  const messages = SUPPORT_MESSAGES[lang] ?? SUPPORT_MESSAGES.en;
  return messages[key].replace(/\{(\w+)\}/g, (match, name: string) => vars[name] ?? match);
}
